"""Host-owned turn decisions and ordered speech lifecycle hooks.

Only the adapters supply current student input. Tool/model arguments never enter
the input seam. Notices and exact host read-backs use the already metered TTS
route; full playback is a separate receipt from starting an output attempt.
"""

from __future__ import annotations

from collections.abc import Awaitable, Callable
from dataclasses import dataclass, field

OutputAuthorization = Callable[[], Awaitable[None]]


@dataclass(frozen=True)
class HostReply:
    answer: str
    authorize: OutputAuthorization | None = field(default=None, repr=False)


class HostReplyRequired(Exception):
    """Realtime must hand this exact host text to its owner's existing TTS path."""

    def __init__(self, question: str, answer: str, authorize: OutputAuthorization | None = None):
        # Never put private input, event fields or reply text in exception args.
        super().__init__("A host-owned reply is required")
        self.question, self.answer, self.authorize = question, answer, authorize


class HostTurnHooks:
    """No-op base makes independently owned host features safely composable."""

    @property
    def needs_input(self) -> bool:
        return False

    @property
    def needs_output_boundary(self) -> bool:
        return False

    async def input(self, question: str) -> HostReply | None:
        return None

    async def after_tool(self) -> HostReply | None:
        return None

    async def before_output(self) -> str | None:
        return None

    async def notice_played(self, notice: str) -> None:
        pass

    async def output_started(self) -> None:
        """Record exposure immediately before actual response audio publication."""

    async def played(self, answer: str) -> None:
        pass

    def invalidate(self, reason: str) -> None:
        pass

    async def failed(self) -> None:
        pass

    async def close(self) -> None:
        pass


class CompositeHostTurnHooks(HostTurnHooks):
    def __init__(self, *hooks: HostTurnHooks):
        self.hooks = hooks
        self._notices: list[tuple[HostTurnHooks, str]] = []

    @property
    def needs_input(self) -> bool:
        return any(hook.needs_input for hook in self.hooks)

    @property
    def needs_output_boundary(self) -> bool:
        return any(hook.needs_output_boundary for hook in self.hooks)

    async def input(self, question: str) -> HostReply | None:
        for hook in self.hooks:
            reply = await hook.input(question)
            if reply is not None:
                return reply
        return None

    async def after_tool(self) -> HostReply | None:
        for hook in self.hooks:
            reply = await hook.after_tool()
            if reply is not None:
                return reply
        return None

    async def before_output(self) -> str | None:
        self._notices = []
        for hook in self.hooks:
            notice = await hook.before_output()
            if notice:
                self._notices.append((hook, notice))
        return " ".join(text for _, text in self._notices) or None

    async def notice_played(self, notice: str) -> None:
        # Only the exact notice generated by this boundary can release it.
        if notice != " ".join(text for _, text in self._notices):
            self.invalidate("notice_changed")
            return
        notices, self._notices = self._notices, []
        for hook, text in notices:
            await hook.notice_played(text)

    async def output_started(self) -> None:
        for hook in self.hooks:
            await hook.output_started()

    async def played(self, answer: str) -> None:
        for hook in self.hooks:
            await hook.played(answer)

    def invalidate(self, reason: str) -> None:
        self._notices = []
        for hook in self.hooks:
            hook.invalidate(reason)

    async def failed(self) -> None:
        for hook in self.hooks:
            await hook.failed()

    async def close(self) -> None:
        self.invalidate("closed")
        for hook in self.hooks:
            await hook.close()
